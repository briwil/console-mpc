FRAMES = [globals()["frame_%03d" % (n + 1)] for n in range(len(HOLDS))]


def frame_at(t):
    """The frame to show t seconds after it began: the last one stays."""
    tick = int(t * FPS)
    for fn, hold in zip(FRAMES, HOLDS):
        if tick < hold:
            return fn
        tick -= hold
    return FRAMES[-1]
