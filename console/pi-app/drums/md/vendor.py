"""Copies the Machinedrum sounds from OP-XY-MNMD into the console and writes the tables the glue needs.

The sounds are mmockett/OP-XY-MNMD (MIT, see LICENSE-OP-XY-MNMD): the Machinedrum's TRX, EFM, P-I and GND
machines written from scratch in fixed-point C++ for the OP-XY. They need three small headers from the
Open-XY SDK (etcetc000/open-xy, MIT, LICENSE-OPEN-XY). E12 isn't here: it needs samples from your own ROM.

To update, check both out side by side and run:

    python3 vendor.py /path/to/OP-XY-MNMD /path/to/open-xy

It copies voices/ and lib/ into vendor/, the SDK headers into vendor/opxy/, and writes md_catalog.h and
md_dispatch.h here. Commit what it writes. (It needs node for the machines without fitted presets, as
OP-XY-MNMD's own generator does.)
"""
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main(mnmd, sdk):
    sys.path.insert(0, os.path.join(mnmd, "tools"))
    import catalog
    import make_engine as me
    os.chdir(mnmd)                                   # make_engine's defaults() runs node from there

    names = [n for n, (inst, _, _) in catalog.MACHINES.items() if inst == "md" and not n.startswith("E12")]
    names.sort(key=lambda n: (["TRX", "EFM", "PI", "GND"].index(n.split("-")[0]), catalog.MACHINES[n][1]))
    headers = sorted({me.sound_header(n) for n in names})

    # the sound code, as it is
    out = os.path.join(HERE, "vendor")
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(os.path.join(out, "opxy"))
    for h in headers:
        shutil.copy(os.path.join(mnmd, "voices", h + ".hpp"), out)
    for f in os.listdir(os.path.join(mnmd, "lib")):
        if f.endswith(".hpp") and not f.endswith("_view.hpp") and f not in ("md_rig.hpp",):
            shutil.copy(os.path.join(mnmd, "lib", f), out)
    for f in ("audio.hpp", "q31.hpp", "types.hpp"):
        shutil.copy(os.path.join(sdk, "sdk", "include", "opxy", f), os.path.join(out, "opxy"))
    shutil.copy(os.path.join(mnmd, "LICENSE"), os.path.join(HERE, "LICENSE-OP-XY-MNMD"))
    shutil.copy(os.path.join(sdk, "LICENSE"), os.path.join(HERE, "LICENSE-OPEN-XY"))

    # md_catalog.h: every machine (its eight slots and defaults) and the starting kit
    rows = []
    for n in names:
        slots = catalog.MACHINES[n][2]
        d = me.defaults(n)
        vals = [int(round(v)) if s else 0 for v, s in zip(d, slots)]
        labels = ", ".join('"%s"' % (s or "") for s in slots)
        rows.append('    {"%s", "%s", {%s}, {%s}},' % (n, n.split("-", 1)[1], labels, ", ".join(map(str, vals))))
    kit = []
    for role, name, model, raw in me.kit_keys("mdtrx")[:16]:
        kit.append('    {"%s", %d, {%s}},   // %s' % (role, names.index(name), ", ".join(map(str, raw)), name))
    with open(os.path.join(HERE, "md_catalog.h"), "w") as f:
        f.write("""// Generated by vendor.py from OP-XY-MNMD's tools/catalog.py: don't edit, run vendor.py again.
// Every Machinedrum machine here (TRX, EFM, P-I, GND), its eight controls as the original's page
// shows them ("" = an empty slot) and its defaults 0..127; then the starting kit: the Machinedrum's
// default kit, BD SD HT MT LT CP RS CB CH OH RC CC M1..M4.
#pragma once
struct MdMachine { const char* name; const char* shortname; const char* labels[8]; unsigned char defaults[8]; };
static const int MD_MACHINES = %d;
static const MdMachine md_machines[MD_MACHINES] = {
%s
};
struct MdKitLane { const char* role; int machine; unsigned char values[8]; };
static const int MD_LANES = 16;
static const MdKitLane md_kit[MD_LANES] = {
%s
};
""" % (len(names), "\n".join(rows), "\n".join(kit)))

    # md_dispatch.h: one State for any machine, and reset / trigger / render by machine number
    def cases(call):
        return "\n".join("    case %d: md::%s::%s; break;" % (i, me.slug(n), call.replace("U", "u.m%d" % i))
                         for i, n in enumerate(names))
    with open(os.path.join(HERE, "md_dispatch.h"), "w") as f:
        f.write("""// Generated by vendor.py: don't edit, run vendor.py again.
#pragma once
%s

union MdState {
%s
};

inline void md_reset(int m, MdState& u, md::Common& c, opxy::u32 owner) {
    switch (m) {
%s
    default: break;
    }
}
inline void md_trigger(int m, MdState& u, md::Common& c) {
    switch (m) {
%s
    default: break;
    }
}
inline void md_render(int m, MdState& u, md::Common& c, opxy::i32* out, const opxy::i32* slots, const opxy::u32* pitch) {
    switch (m) {
%s
    default: for (unsigned i = 0; i < opxy::block_frames; ++i) out[i] = 0; break;
    }
}
""" % ("\n".join('#include "%s.hpp"' % h for h in headers),
       "\n".join("    md::%s::State m%d;" % (me.slug(n), i) for i, n in enumerate(names)),
       cases("reset(U, c, owner)"), cases("trigger(U, c)"), cases("render(U, c, out, slots, pitch)")))
    print("%d machines, %d headers" % (len(names), len(headers)))


if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]), os.path.abspath(sys.argv[2]))
